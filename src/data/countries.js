function resolveName(code) {
  let intlName = '';
  try {
    intlName = new Intl.DisplayNames(['en'], { type: 'region' }).of(code) || '';
  } catch {
    intlName = '';
  }
  // Hermes sometimes returns the code itself — treat that as missing.
  if (intlName && intlName.toUpperCase() !== code.toUpperCase() && intlName.length > 2) {
    return intlName;
  }
  return FALLBACK_NAMES[code] || code;
}

let cached;

export default function getCountries() {
  if (cached) return cached;
  cached = CODES.split(' ')
    .map(code => ({ code, name: resolveName(code) }))
    .sort((a, b) => a.name.localeCompare(b.name, 'en'));
  return cached;
}
